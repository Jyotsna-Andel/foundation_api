#!/usr/bin/env node
// Rebuilds docs/knowledge/INDEX.md from the cards and transcripts, so the
// tables are never edited by hand.
// Usage (repo root): node .claude/skills/handover-interview/scripts/index.mjs [--knowledge docs/knowledge]

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { listKnowledgeFiles, readKnowledge } from './lib/knowledge.mjs';

const argv = process.argv.slice(2);
const i = argv.indexOf('--knowledge');
const knowledgeRel = i >= 0 && argv[i + 1] ? argv[i + 1] : 'docs/knowledge';
const knowledgeDir = join(process.cwd(), knowledgeRel);

const cell = (v) => String(v ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ') || '—';
const table = (headers, rows) => {
  const body = rows.length ? rows : [headers.map(() => '—')];
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...body.map((r) => `| ${r.map(cell).join(' | ')} |`),
  ].join('\n');
};

const { cards, sessions } = listKnowledgeFiles(knowledgeDir);

const sessionRows = [];
const coverageByPerson = new Map();
for (const rel of sessions) {
  const { data, body } = readKnowledge(knowledgeDir, rel);
  if (!data) continue;
  const topics = (body.match(/^## Topic /gm) ?? []).length;
  sessionRows.push([`[${rel.replace('sessions/', '')}](${rel})`, data.person, data.date, data.status, topics]);
  const prev = coverageByPerson.get(data.person);
  if (!prev || (data.date ?? '') >= prev.date) {
    coverageByPerson.set(data.person, {
      date: data.date,
      before: data.coverage_before,
      after: data.coverage_after,
    });
  }
}

const cardRows = cards.map((rel) => {
  const { data } = readKnowledge(knowledgeDir, rel);
  const files = (Array.isArray(data?.files) ? data.files : [])
    .map((f) => `\`${typeof f === 'string' ? f : f.path}${f.lines ? `:${f.lines}` : ''}\``)
    .join(', ');
  return [`[${data?.title ?? rel}](${rel})`, data?.owner, files || '—', data?.captured, data?.confidence];
});

const coverageRows = [...coverageByPerson.entries()].map(([person, c]) => [
  person,
  `${c.before ?? '?'} → ${c.after ?? '?'}`,
  c.date,
]);

const content = `# Knowledge base

<!-- Generated by .claude/skills/handover-interview/scripts/index.mjs: do not edit by hand. -->

Answers that only one person knew, captured in handover interviews (\`/handover-interview\`) and searchable with \`/ask-why\`.

- **Cards** (folders per area) are approved summaries, linked to code and commits.
- **Transcripts** ([sessions/](sessions/)) hold every question and answer word for word, reviewed by the expert, so anyone can check a card against the original answer.

## Coverage

${table(['Person', 'Knowledge at risk (before → after)', 'Last session'], coverageRows)}

Recalculate any time: \`node .claude/skills/handover-interview/scripts/ownership.mjs --author "<email>"\`

## Cards

${table(['Card', 'Owner', 'Files', 'Captured', 'Confidence'], cardRows)}

## Sessions

${table(['Transcript', 'Person', 'Date', 'Status', 'Topics'], sessionRows)}
`;

writeFileSync(join(knowledgeDir, 'INDEX.md'), content);
console.log(`Wrote ${knowledgeRel}/INDEX.md: ${cardRows.length} card(s), ${sessionRows.length} session(s).`);
